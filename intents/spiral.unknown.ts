import { SkillResponseBuilder, AliceResponse } from '@kirillchervotkin/alice-nestjs-framework';

/**
 * Обработка любых неизвестных команд
 * 
 * Положительные тесты:
 * - "пон"
 * - "блабла"
 * - "хрень"
 * - "ерунда"
 * - "что это"
 * - "не понимаю"
 * - "хм"
 * - "эм"
 * - "чего"
 * - "что"
 * - "как"
 * 
 * Отрицательные тесты:
 * - "да"
 * - "нет"
 * - "помощь"
 * - "начать тест"
 * - "выход"
 * - "описание"
 * - "желтый"
 * - "красный"
 */

// Грамматика Яндекса с регулярными выражениями:
/*
root:
  .+ |
  $AnyWord+ |
  ($AnyWord .+)? |
  (.+ $AnyWord)+

$AnyWord:
  %lemma
  абракадабра | блабла | хрень | ерунда | пон | рандом | тест | проверка | слово | любой | текст | неизвестная | команда
*/

// Паттерн: универсальный catch-all с regex и нетерминалами
// .+ - любые символы (один или больше)
// $AnyWord - распознаваемые "мусорные" слова с лемматизацией
// Приоритет: 1
export function spiralUnknown(_context: any, matches: RegExpMatchArray): AliceResponse {
    // Этот интент обрабатывается в AliceController.handleUnknownIntent()
    // Здесь просто fallback на случай если что-то пошло не так
    return new SkillResponseBuilder(
        'Извините, ваше слово мне не понятно. Попробуйте сказать "о навыке".'
    )
      .setButtons([
        { title: "О навыке", hide: true }
      ])
      .build();
}

